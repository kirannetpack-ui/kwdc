    <h2>1. Fleet & Driver Regulatory Standards (DoTM Nepal)</h2>
    <p>
        Commercial road freight transport within the Kathmandu Valley and connecting arterial national highways (Tribhuvan Highway, Prithvi Highway, East-West Highway) is governed by stringent vehicle standards:
    </p>
    <ul>
        <li><strong>Valid Category Driver Licenses:</strong> Drivers operating freight vehicles must possess a valid commercial driver's license (Category B for pickups, Category G for medium/heavy commercial trucks) registered with the Department of Transport Management.</li>
        <li><strong>Vehicle Fitness & Pollution Certificates:</strong> All registered transport vehicles must pass periodic mechanical fitness inspections and display valid Nepal Green Pollution Emission stickers.</li>
        <li><strong>Maximum Driving Hours & Rest Cycles:</strong> To eliminate fatigue-related highway risks, long-haul highway drivers are mandated to take a minimum 30-minute rest after every 4 hours of continuous transit.</li>
        <li><strong>Mandatory Third-Party & Cargo Liability Insurance:</strong> No transport vehicle may depart any KTM-WDC hub without active vehicle third-party insurance and minimum commercial carrier coverage.</li>
    </ul>

    <h2>2. Commercial Warehouse Building & Fire Codes (NBC Standards)</h2>
    <p>
        Storage facilities certified on KTM-WDC must comply with the National Building Code of Nepal (NBC 105, NBC 206) and fire prevention standards:
    </p>
    <ul>
        <li><strong>Structural Integrity & Loading Limits:</strong> Certified floor load ratings must be prominently displayed across all loading bays. Stack heights must maintain a minimum 1.0-meter clearance below roof trusses and sprinkler heads.</li>
        <li><strong>Fire Extinguishers & Suppression:</strong> Operational ABC dry chemical powder (DCP) and CO2 extinguishers must be stationed at intervals of no more than 20 meters, inspected and recharged every 12 months.</li>
        <li><strong>CCTV Surveillance Infrastructure:</strong> Warehouses must maintain 24/7 continuous perimeter and interior aisle camera recording with minimum 30-day archival retention.</li>
        <li><strong>Clear Emergency Egress:</strong> Loading docks and emergency exit passages must remain entirely free of carton obstruction at all times.</li>
    </ul>

    <h2>3. Cold Chain Storage & HACCP Protocols</h2>
    <p>
        Perishable foods, dairy goods, and temperature-sensitive pharmaceuticals stored within KTM-WDC cold storage facilities adhere to temperature logging standards:
    </p>
    <ul>
        <li><strong>Automated Telemetric Logging:</strong> Temperature and humidity sensors record ambient levels every 15 minutes with automated alert thresholds.</li>
        <li><strong>Dual-Fuel Auxiliary Generator Backup:</strong> Facilities must feature automatic transfer switches (ATS) with standby diesel generators capable of sustaining cold rooms indefinitely during grid outages.</li>
    </ul>

    <h2>4. Equipment Certification & Operator Licensing</h2>
    <p>
        Forklifts, pallet stackers, and heavy rigging machinery must undergo bi-annual preventive mechanical maintenance. Forklift operators must complete verified operator safety training before operating equipment in busy warehouse loading yards.
    </p>

    <h2>5. Security Agency & Personnel Integrity</h2>
    <p>
        Security agencies registered on the platform must be licensed by the Ministry of Home Affairs. Stationed personnel are subject to formal background checks, zero criminal record verification, and emergency response training.
    </p>
